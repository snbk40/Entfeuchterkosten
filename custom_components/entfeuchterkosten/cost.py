"""Turns a power reading over time into energy and costs. No Home Assistant code.

The power is taken to stay at its last value until the next reading comes
(left Riemann sum). That matches a smart plug, whose reading jumps when the
compressor of the dehumidifier switches on or off.

Power generated by solar panels at the same moment is free: only the part of
the dehumidifier's power above it is chargeable and costs money.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import UTC, date, datetime, time, timedelta
from enum import StrEnum
import math

# Factors from the supported units of a power sensor to watts
POWER_UNITS: dict[str, float] = {
    "mW": 0.001,
    "W": 1.0,
    "kW": 1000.0,
    "MW": 1_000_000.0,
}


class Period(StrEnum):
    """The periods after which a cost sensor starts again at zero."""

    DAY = "day"
    MONTH = "month"
    YEAR = "year"


def to_watts(value: str | float | None, unit: str | None) -> float | None:
    """Return a power reading in watts, or None if it cannot be used."""
    factor = POWER_UNITS.get(unit or "W")
    if factor is None or value is None:
        return None
    try:
        watts = float(value) * factor
    except ValueError:
        return None
    return watts if math.isfinite(watts) else None


def _midnight(day: date, like: datetime) -> datetime:
    """Return midnight at the start of a day, in the time zone of `like`."""
    return datetime.combine(day, time(0), tzinfo=like.tzinfo)


def period_start(period: Period, when: datetime) -> datetime:
    """Return the local start of the period that `when` lies in."""
    day = when.date()
    if period is Period.MONTH:
        day = day.replace(day=1)
    elif period is Period.YEAR:
        day = day.replace(month=1, day=1)
    return _midnight(day, when)


def _hours(start: datetime, end: datetime) -> float:
    # In UTC: Python ignores a change of the UTC offset (summer time) when
    # subtracting two times of the same time zone.
    return (end.astimezone(UTC) - start.astimezone(UTC)).total_seconds() / 3600


@dataclass
class PeriodCost:
    """The costs since the start of the current day, month or year."""

    start: datetime
    cost: float = 0.0


@dataclass
class CostMeter:
    """Adds up the energy and the costs of one dehumidifier.

    The energy is everything the dehumidifier uses; the costs count only its
    chargeable power, the part not covered by solar power. All times must carry the local time zone, which decides where a day,
    month or year begins.
    """

    price: float  # per kWh
    now: datetime
    total_kwh: float = 0.0
    total_cost: float = 0.0
    periods: dict[Period, PeriodCost] = field(default_factory=dict)
    _watts: float | None = field(default=None, init=False)
    _solar_watts: float = field(default=0.0, init=False)
    _since: datetime | None = field(default=None, init=False)

    def __post_init__(self) -> None:
        """Start every period at the current time."""
        for period in Period:
            self.periods.setdefault(period, PeriodCost(period_start(period, self.now)))

    @property
    def watts(self) -> float | None:
        """Return the power of the dehumidifier that is counted at the moment."""
        return self._watts

    @property
    def chargeable_watts(self) -> float | None:
        """Return the part of the power that is not covered by solar power."""
        if self._watts is None:
            return None
        return max(self._watts - self._solar_watts, 0.0)

    @property
    def saved_watts(self) -> float | None:
        """Return the part of the power that solar power covers, for free."""
        if self._watts is None:
            return None
        return min(self._watts, self._solar_watts)

    def set_power(self, watts: float | None, now: datetime) -> None:
        """Count up to now, then go on with a new power reading.

        None means the power is unknown: the time until the next known
        reading is not counted. Negative power counts as zero.
        """
        self.advance(now)
        self._watts = None if watts is None else max(watts, 0.0)
        self._since = now

    def set_solar_power(self, watts: float | None, now: datetime) -> None:
        """Count up to now, then go on with a new solar power reading.

        None means the solar power is unknown, which many inverters report at
        night: it counts as zero, so the whole power is chargeable.
        """
        self.advance(now)
        self._solar_watts = 0.0 if watts is None else max(watts, 0.0)

    def advance(self, now: datetime) -> None:
        """Count the current power up to now."""
        start = self._since
        chargeable = self.chargeable_watts
        if start is not None and self._watts is not None and now > start:
            assert chargeable is not None
            # Split at every midnight, so each part lands in the right periods.
            while start < now:
                next_midnight = _midnight(start.date() + timedelta(days=1), start)
                end = min(now, next_midnight)
                hours = _hours(start, end)
                self._add(start, self._watts * hours / 1000, chargeable * hours / 1000)
                start = end
        if self._since is None or now > self._since:
            self._since = now
        self._roll(now)

    def restore_period(self, period: Period, cost: float, start: datetime) -> None:
        """Add a cost kept from before a restart, if its period is still running."""
        current = self.periods[period]
        if start == current.start:
            current.cost += cost

    def _add(self, start: datetime, kwh: float, chargeable_kwh: float) -> None:
        cost = chargeable_kwh * self.price
        self.total_kwh += kwh
        self.total_cost += cost
        self._roll(start)
        for current in self.periods.values():
            current.cost += cost

    def _roll(self, when: datetime) -> None:
        """Start a period again at zero once a new day, month or year begins."""
        for period, current in self.periods.items():
            start = period_start(period, when)
            if start > current.start:
                self.periods[period] = PeriodCost(start)
